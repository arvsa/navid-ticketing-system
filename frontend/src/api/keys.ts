// Query keys: the single source for caching and invalidation.
export const keys = {
  me: ["me"] as const,
  branches: ["branches"] as const,
  branch: (id: string) => ["branches", id] as const,
  members: (branchId: string, extra?: object) => ["branches", branchId, "members", extra ?? {}] as const,
  groups: (branchId: string, extra?: object) => ["branches", branchId, "groups", extra ?? {}] as const,
  groupMembers: (branchId: string, groupId: string) =>
    ["branches", branchId, "members", { group_id: groupId }] as const,
  effective: (branchId: string, userId: string) => ["effective-permissions", branchId, userId] as const,
  people: ["people"] as const,
  myGroups: (branchId: string) => ["my-groups", branchId] as const,
  issues: ["issues"] as const,
  issueList: (filters: object) => ["issues", "list", filters] as const,
  issue: (id: string) => ["issues", "detail", id] as const,
  issueByNumber: (n: number) => ["issues", "by-number", n] as const,
  comments: (id: string, workItemId?: string) => ["issues", id, "comments", workItemId ?? null] as const,
  reports: (id: string) => ["issues", id, "reports"] as const,
  history: (id: string) => ["issues", id, "history"] as const,
  workItems: ["work-items"] as const,
  workItemList: (filters: object) => ["work-items", "list", filters] as const,
  calendar: (from: string, to: string, branchId?: string) => ["calendar", from, to, branchId ?? "all"] as const,
  rsvps: (id: string) => ["events", id, "rsvps"] as const,
  notifications: (filters: object) => ["notifications", filters] as const,
  unread: ["notifications", "unread-count"] as const,
  dashboard: (branchId?: string) => ["dashboard", branchId ?? "all"] as const,
  catalog: ["permissions", "catalog"] as const,
  groupGrants: (groupId: string) => ["groups", groupId, "permissions"] as const,
};
